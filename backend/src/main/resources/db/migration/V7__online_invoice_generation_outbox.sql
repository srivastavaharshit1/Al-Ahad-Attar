-- Durable paid online-order invoice generation queue. Additive; V5 and V6 remain unchanged.
-- Orders are discovered from their existing payment/order state by the opt-in worker.

CREATE TABLE billing_online_invoice_job (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id) ON DELETE RESTRICT,
    invoice_id BIGINT NULL UNIQUE REFERENCES billing_invoice(id) ON DELETE RESTRICT,
    job_status VARCHAR(30) NOT NULL CHECK (job_status IN (
        'PENDING', 'PROCESSING', 'RETRY_WAIT', 'BLOCKED_CONFIGURATION',
        'COMPLETED', 'FAILED', 'SKIPPED_INELIGIBLE'
    )),
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    next_attempt_at TIMESTAMPTZ NULL,
    processing_started_at TIMESTAMPTZ NULL,
    last_error_code VARCHAR(100) NULL,
    last_error_summary VARCHAR(500) NULL,
    requested_by_user_id BIGINT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((job_status = 'COMPLETED' AND invoice_id IS NOT NULL)
        OR (job_status <> 'COMPLETED'))
);

CREATE INDEX idx_billing_online_invoice_job_due
    ON billing_online_invoice_job (job_status, next_attempt_at, id);

CREATE TABLE billing_online_invoice_job_attempt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL REFERENCES billing_online_invoice_job(id) ON DELETE RESTRICT,
    attempt_number INTEGER NOT NULL CHECK (attempt_number > 0),
    outcome VARCHAR(30) NOT NULL,
    error_code VARCHAR(100) NULL,
    error_summary VARCHAR(500) NULL,
    started_at TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ NULL,
    UNIQUE (job_id, attempt_number)
);

CREATE INDEX idx_billing_online_invoice_attempt_history
    ON billing_online_invoice_job_attempt (job_id, attempt_number);

CREATE TABLE billing_online_invoice_job_retry_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL REFERENCES billing_online_invoice_job(id) ON DELETE RESTRICT,
    idempotency_key VARCHAR(160) NOT NULL UNIQUE,
    requested_by_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_billing_online_invoice_retry_job
    ON billing_online_invoice_job_retry_request (job_id, requested_at DESC);

CREATE TRIGGER billing_online_invoice_job_attempt_immutable
    BEFORE UPDATE OR DELETE ON billing_online_invoice_job_attempt
    FOR EACH ROW EXECUTE FUNCTION billing_reject_immutable_snapshot_mutation();

CREATE TRIGGER billing_online_invoice_retry_request_immutable
    BEFORE UPDATE OR DELETE ON billing_online_invoice_job_retry_request
    FOR EACH ROW EXECUTE FUNCTION billing_reject_immutable_snapshot_mutation();

COMMENT ON TABLE billing_online_invoice_job IS
    'Durable worker queue for invoices discovered from eligible paid online orders; it does not modify orders or payment state.';
COMMENT ON TABLE billing_online_invoice_job_attempt IS
    'Append-only attempt history for asynchronous online invoice generation.';
