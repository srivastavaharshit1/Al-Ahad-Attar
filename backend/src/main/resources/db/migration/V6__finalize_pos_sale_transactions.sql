-- POS sale finalization extensions. Forward-only and additive: V5 is not rewritten and
-- existing sale, invoice, discount, access, consent, delivery, and audit rows are retained.

ALTER TABLE billing_pos_sale
    ADD COLUMN created_by_email_snapshot VARCHAR(254) NULL,
    ADD COLUMN completed_at TIMESTAMPTZ NULL,
    ADD COLUMN confirmed_quote_fingerprint CHAR(64) NULL;

ALTER TABLE billing_pos_sale_line
    ADD COLUMN line_key VARCHAR(64) NULL,
    ADD COLUMN is_free_item BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN free_promotion_id BIGINT NULL,
    ADD CONSTRAINT ck_billing_pos_sale_line_free_promotion
        CHECK ((is_free_item = TRUE AND free_promotion_id IS NOT NULL)
            OR (is_free_item = FALSE AND free_promotion_id IS NULL));

CREATE UNIQUE INDEX uq_billing_pos_sale_line_key
    ON billing_pos_sale_line (sale_id, line_key)
    WHERE line_key IS NOT NULL;

CREATE INDEX idx_billing_pos_sale_line_free_promotion
    ON billing_pos_sale_line (free_promotion_id)
    WHERE free_promotion_id IS NOT NULL;

-- The promotion ID and display snapshots intentionally have no FK to the mutable promotion
-- catalogue. Historical sale records must survive promotion edits or deletion.
CREATE TABLE billing_pos_sale_promotion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT NOT NULL REFERENCES billing_pos_sale(id) ON DELETE RESTRICT,
    promotion_id BIGINT NOT NULL,
    promotion_name_snapshot VARCHAR(255) NOT NULL,
    promotion_code_snapshot VARCHAR(100) NULL,
    promotion_type_snapshot VARCHAR(40) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (sale_id, promotion_id)
);

CREATE INDEX idx_billing_pos_sale_promotion_sale
    ON billing_pos_sale_promotion (sale_id, id);

-- Reuse the existing global promotion claim counter while linking its redemption record to
-- the dedicated POS sale aggregate. Existing order redemption rows remain unchanged.
ALTER TABLE promotion_redemption
    ADD COLUMN pos_sale_id BIGINT NULL REFERENCES billing_pos_sale(id) ON DELETE RESTRICT,
    ADD CONSTRAINT ck_promotion_redemption_single_source
        CHECK (NOT (order_id IS NOT NULL AND pos_sale_id IS NOT NULL));

CREATE INDEX idx_promotion_redemption_pos_sale
    ON promotion_redemption (pos_sale_id)
    WHERE pos_sale_id IS NOT NULL;

ALTER TABLE billing_invoice_line
    ADD COLUMN is_free_item BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN free_promotion_id BIGINT NULL,
    ADD CONSTRAINT ck_billing_invoice_line_free_promotion
        CHECK ((is_free_item = TRUE AND free_promotion_id IS NOT NULL)
            OR (is_free_item = FALSE AND free_promotion_id IS NULL));

CREATE INDEX idx_billing_invoice_line_free_promotion
    ON billing_invoice_line (free_promotion_id)
    WHERE free_promotion_id IS NOT NULL;

-- Finalized POS sale snapshots are append-only. V5's shared immutable trigger function is reused.
CREATE TRIGGER billing_pos_sale_immutable
    BEFORE UPDATE OR DELETE ON billing_pos_sale
    FOR EACH ROW EXECUTE FUNCTION billing_reject_immutable_snapshot_mutation();

CREATE TRIGGER billing_pos_sale_line_immutable
    BEFORE UPDATE OR DELETE ON billing_pos_sale_line
    FOR EACH ROW EXECUTE FUNCTION billing_reject_immutable_snapshot_mutation();

CREATE TRIGGER billing_pos_sale_promotion_immutable
    BEFORE UPDATE OR DELETE ON billing_pos_sale_promotion
    FOR EACH ROW EXECUTE FUNCTION billing_reject_immutable_snapshot_mutation();

CREATE TRIGGER billing_pos_tender_immutable
    BEFORE UPDATE OR DELETE ON billing_pos_tender
    FOR EACH ROW EXECUTE FUNCTION billing_reject_immutable_snapshot_mutation();

