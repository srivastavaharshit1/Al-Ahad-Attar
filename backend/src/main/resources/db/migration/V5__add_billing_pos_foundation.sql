CREATE TABLE billing_discount_policy (
    policy_version BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_by_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uq_billing_discount_policy_one_active
    ON billing_discount_policy ((enabled))
    WHERE enabled = TRUE;

CREATE TABLE billing_staff_discount_limit (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    policy_version BIGINT NOT NULL REFERENCES billing_discount_policy(policy_version) ON DELETE RESTRICT,
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    max_item_fixed_amount NUMERIC(12, 2) NULL CHECK (max_item_fixed_amount >= 0),
    max_item_percentage NUMERIC(5, 2) NULL CHECK (max_item_percentage >= 0 AND max_item_percentage <= 100),
    max_sale_fixed_amount NUMERIC(12, 2) NULL CHECK (max_sale_fixed_amount >= 0),
    max_sale_percentage NUMERIC(5, 2) NULL CHECK (max_sale_percentage >= 0 AND max_sale_percentage <= 100),
    max_combined_amount NUMERIC(12, 2) NULL CHECK (max_combined_amount >= 0),
    max_combined_percentage NUMERIC(5, 2) NULL CHECK (max_combined_percentage >= 0 AND max_combined_percentage <= 100),
    configured_by_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    configured_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, policy_version)
);

CREATE TABLE billing_discount_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_key UUID NOT NULL UNIQUE,
    quote_key UUID NOT NULL,
    basket_hash CHAR(64) NOT NULL,
    requested_by_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    scope VARCHAR(10) NOT NULL CHECK (scope IN ('ITEM', 'SALE')),
    discount_type VARCHAR(10) NOT NULL CHECK (discount_type IN ('FIXED', 'PERCENT')),
    target_line_key VARCHAR(100) NULL,
    requested_value NUMERIC(12, 2) NOT NULL CHECK (requested_value > 0),
    calculated_amount NUMERIC(12, 2) NOT NULL CHECK (calculated_amount >= 0),
    calculation_base NUMERIC(12, 2) NOT NULL CHECK (calculation_base >= 0),
    reason VARCHAR(1000) NOT NULL CHECK (LENGTH(TRIM(reason)) > 0),
    policy_version BIGINT NULL REFERENCES billing_discount_policy(policy_version) ON DELETE RESTRICT,
    request_status VARCHAR(30) NOT NULL CHECK (request_status IN (
        'PENDING_APPROVAL', 'APPROVED', 'REJECTED', 'APPLIED', 'EXPIRED'
    )),
    request_hash CHAR(64) NOT NULL,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NULL,
    decided_by_user_id BIGINT NULL REFERENCES users(id) ON DELETE RESTRICT,
    decided_at TIMESTAMPTZ NULL,
    CHECK ((scope = 'ITEM' AND target_line_key IS NOT NULL) OR (scope = 'SALE' AND target_line_key IS NULL))
);

CREATE INDEX idx_billing_discount_request_status
    ON billing_discount_request (request_status, requested_at);

CREATE UNIQUE INDEX uq_billing_discount_request_quote_item
    ON billing_discount_request (quote_key, target_line_key) WHERE scope = 'ITEM';

CREATE UNIQUE INDEX uq_billing_discount_request_quote_sale
    ON billing_discount_request (quote_key) WHERE scope = 'SALE';

CREATE TABLE billing_discount_audit_event (
