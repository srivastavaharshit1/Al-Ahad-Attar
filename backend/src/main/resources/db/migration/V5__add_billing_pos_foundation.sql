CREATE TABLE billing_discount_application (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT NOT NULL REFERENCES billing_pos_sale(id) ON DELETE RESTRICT,
    sale_line_id BIGINT NULL REFERENCES billing_pos_sale_line(id) ON DELETE RESTRICT,
    scope VARCHAR(10) NOT NULL CHECK (scope IN ('ITEM', 'SALE')),
    discount_type VARCHAR(10) NOT NULL CHECK (discount_type IN ('FIXED', 'PERCENT')),
    requested_value NUMERIC(12, 2) NOT NULL CHECK (requested_value > 0),
    applied_amount NUMERIC(12, 2) NOT NULL CHECK (applied_amount >= 0),
    calculation_base NUMERIC(12, 2) NOT NULL CHECK (calculation_base >= 0),
    staff_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    reason VARCHAR(1000) NOT NULL CHECK (LENGTH(TRIM(reason)) > 0),
    approver_user_id BIGINT NULL REFERENCES users(id) ON DELETE RESTRICT,
    policy_version BIGINT NULL REFERENCES billing_discount_policy(policy_version) ON DELETE RESTRICT,
    approved_at TIMESTAMPTZ NULL,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((scope = 'ITEM' AND sale_line_id IS NOT NULL) OR (scope = 'SALE' AND sale_line_id IS NULL)),
    CHECK (discount_type <> 'PERCENT' OR requested_value <= 100)
);

CREATE INDEX idx_billing_discount_application_sale
    ON billing_discount_application (sale_id, applied_at);

CREATE TABLE billing_pos_tender (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT NOT NULL UNIQUE REFERENCES billing_pos_sale(id) ON DELETE RESTRICT,
    tender_method VARCHAR(10) NOT NULL CHECK (tender_method IN ('CASH', 'UPI', 'CARD')),
    sale_payable_amount NUMERIC(12, 2) NOT NULL CHECK (sale_payable_amount >= 0),
    amount_received NUMERIC(12, 2) NOT NULL CHECK (amount_received >= 0),
    change_returned NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (change_returned >= 0),
    amount_applied NUMERIC(12, 2) NOT NULL CHECK (amount_applied >= 0),
    transaction_reference VARCHAR(200) NULL,
    recorded_by_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (amount_applied = sale_payable_amount),
    CHECK ((tender_method = 'CASH' AND amount_received - change_returned = amount_applied)
        OR (tender_method IN ('UPI', 'CARD') AND change_returned = 0 AND amount_received = amount_applied))
);

