-- Invoice snapshots, line snapshots, PDF bytes, and delivery attempt history are append-only.
CREATE FUNCTION billing_reject_immutable_snapshot_mutation() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Billing snapshot rows are immutable';
    RETURN OLD;
END;
$$;

CREATE TRIGGER billing_invoice_immutable
    BEFORE UPDATE OR DELETE ON billing_invoice
    FOR EACH ROW EXECUTE FUNCTION billing_reject_immutable_snapshot_mutation();

CREATE TRIGGER billing_invoice_line_immutable
    BEFORE UPDATE OR DELETE ON billing_invoice_line
    FOR EACH ROW EXECUTE FUNCTION billing_reject_immutable_snapshot_mutation();

CREATE TRIGGER billing_invoice_pdf_immutable
    BEFORE UPDATE OR DELETE ON billing_invoice_pdf
    FOR EACH ROW EXECUTE FUNCTION billing_reject_immutable_snapshot_mutation();

CREATE TRIGGER billing_delivery_attempt_immutable
    BEFORE UPDATE OR DELETE ON billing_invoice_delivery_attempt
    FOR EACH ROW EXECUTE FUNCTION billing_reject_immutable_snapshot_mutation();

CREATE TRIGGER billing_consent_event_immutable
    BEFORE UPDATE OR DELETE ON billing_invoice_delivery_consent_event
    FOR EACH ROW EXECUTE FUNCTION billing_reject_immutable_snapshot_mutation();

CREATE TRIGGER billing_discount_application_immutable
    BEFORE UPDATE OR DELETE ON billing_discount_application
    FOR EACH ROW EXECUTE FUNCTION billing_reject_immutable_snapshot_mutation();

CREATE TRIGGER billing_discount_audit_event_immutable
    BEFORE UPDATE OR DELETE ON billing_discount_audit_event
    FOR EACH ROW EXECUTE FUNCTION billing_reject_immutable_snapshot_mutation();

