CREATE TABLE billing_invoice (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_key UUID NOT NULL UNIQUE,
    invoice_number VARCHAR(80) NOT NULL UNIQUE,
    invoice_channel VARCHAR(10) NOT NULL CHECK (invoice_channel IN ('ONLINE', 'POS')),
    source_type VARCHAR(20) NOT NULL CHECK (source_type IN ('ONLINE_ORDER', 'POS_SALE')),
    source_id BIGINT NOT NULL,
    financial_year VARCHAR(20) NOT NULL,
    invoice_status VARCHAR(20) NOT NULL CHECK (invoice_status IN ('FINAL', 'VOID')),
    seller_name_snapshot VARCHAR(240) NOT NULL,
    seller_address_snapshot VARCHAR(1000) NULL,
    seller_phone_snapshot VARCHAR(40) NULL,
    seller_email_snapshot VARCHAR(254) NULL,
    customer_name_snapshot VARCHAR(160) NULL,
    customer_mobile_snapshot VARCHAR(30) NULL,
    customer_email_snapshot VARCHAR(254) NULL,
    subtotal_amount NUMERIC(12, 2) NOT NULL CHECK (subtotal_amount >= 0),
    promotion_discount_amount NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (promotion_discount_amount >= 0),
    manual_discount_amount NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (manual_discount_amount >= 0),
    total_amount NUMERIC(12, 2) NOT NULL CHECK (total_amount >= 0),
    gst_status VARCHAR(20) NOT NULL CHECK (gst_status IN ('UNREGISTERED', 'REGISTERED')),
    gstin_snapshot VARCHAR(15) NULL,
    gst_enabled BOOLEAN NOT NULL,
    tax_mode VARCHAR(20) NOT NULL CHECK (tax_mode IN ('NO_GST', 'GST')),
    invoice_notice_snapshot TEXT NOT NULL,
    issued_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (source_type, source_id),
    CHECK ((invoice_channel = 'ONLINE' AND source_type = 'ONLINE_ORDER')
        OR (invoice_channel = 'POS' AND source_type = 'POS_SALE')),
    CHECK (gst_status <> 'UNREGISTERED' OR (gstin_snapshot IS NULL AND gst_enabled = FALSE AND tax_mode = 'NO_GST'))
);

CREATE INDEX idx_billing_invoice_issued
    ON billing_invoice (issued_at DESC, id DESC);

CREATE INDEX idx_billing_invoice_channel_issued
