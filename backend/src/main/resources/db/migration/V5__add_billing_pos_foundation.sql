-- Billing/POS foundation only. No existing application tables or behavior are altered here.

CREATE TABLE billing_pos_access (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE RESTRICT,
    access_role VARCHAR(20) NOT NULL CHECK (access_role IN ('POS_OWNER', 'POS_STAFF')),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    granted_by_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    granted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revoked_at TIMESTAMPTZ NULL,
    CHECK ((enabled = TRUE AND revoked_at IS NULL) OR enabled = FALSE)
);

CREATE TABLE billing_setup_state (
    singleton_id SMALLINT PRIMARY KEY CHECK (singleton_id = 1),
    owner_bootstrap_completed BOOLEAN NOT NULL DEFAULT FALSE,
    completed_by_user_id BIGINT NULL REFERENCES users(id) ON DELETE RESTRICT,
    completed_at TIMESTAMPTZ NULL
);

INSERT INTO billing_setup_state (singleton_id, owner_bootstrap_completed)
VALUES (1, FALSE);

