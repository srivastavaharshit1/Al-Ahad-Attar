        jdbcTemplate.execute("INSERT INTO billing_invoice (id, invoice_number) VALUES (20, 'POS-2026-27-00020')");
        jdbcTemplate.execute("INSERT INTO billing_invoice (id, invoice_number) VALUES (30, 'POS-2026-27-00030')");

