        // Invoice B (20): Customer explicitly revokes consent at T2 (T2 > T1)
        jdbcTemplate.update("""
                INSERT INTO billing_invoice_delivery_consent (
                    invoice_id, channel, destination, consent_status, wording_version, captured_by_user_id, captured_at, revoked_at
                ) VALUES (20, 'WHATSAPP', '+919876543210', 'REVOKED', 'v1_pos_counter', 1, TIMESTAMP '2026-11-05 10:00:00', TIMESTAMP '2026-11-05 10:00:00')
                """);

